/// Progress of one request. `json` is the event the sidebar UI consumes.
public enum AssistantEvent: Sendable, Equatable {
    case generating(requestID: String, model: String)
    case reading(requestID: String, kind: String, part: Int, of: Int)
    case delta(requestID: String, text: String)
    case done(requestID: String, content: String, stats: ChatStats?, model: String, task: AssistantTask)
    case failed(requestID: String, error: IPCError)

    public var requestID: String {
        switch self {
        case .generating(let id, _), .reading(let id, _, _, _), .delta(let id, _), .done(let id, _, _, _, _), .failed(let id, _): return id
        }
    }

    public var isTerminal: Bool {
        switch self {
        case .done, .failed: return true
        default: return false
        }
    }

    public var json: (type: String, payload: JSONValue) {
        let id = JSONValue.string(requestID)
        switch self {
        case .generating(_, let model):
            return ("agent.status", ["requestId": id, "phase": "generating", "model": .string(model)])
        case .reading(_, let kind, let part, let of):
            return ("agent.status", ["requestId": id, "phase": "reading", "kind": .string(kind), "part": JSONValue(part), "of": JSONValue(of)])
        case .delta(_, let text):
            return ("agent.delta", ["requestId": id, "delta": .string(text)])
        case .done(_, let content, let stats, let model, let task):
            return ("agent.done", ["requestId": id, "content": .string(content), "stats": (try? JSONValue.from(stats)) ?? .null,
                                   "model": .string(model), "task": .string(task.rawValue)])
        case .failed(_, let error):
            return ("agent.error", ["requestId": id, "code": .string(error.code), "message": .string(error.message)])
        }
    }
}

public extension IPCError {
    static func ollamaUnavailable(_ message: String) -> IPCError { IPCError("ollama_unavailable", message) }
    static func ollamaError(_ message: String) -> IPCError { IPCError("ollama_error", message) }
    static func noModel(_ message: String) -> IPCError { IPCError("no_model", message) }
    static let cancelled = IPCError("cancelled", "Request cancelled")
}
