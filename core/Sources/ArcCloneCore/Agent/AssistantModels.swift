    public var videoId: String?
    public var title: String?
    public var author: String?
    public var text: String?
    public var isAutoGenerated: Bool?

    public init(videoId: String? = nil, title: String? = nil, author: String? = nil, text: String? = nil, isAutoGenerated: Bool? = nil) {
        self.videoId = videoId
        self.title = title
        self.author = author
        self.text = text
        self.isAutoGenerated = isAutoGenerated
    }
}

public struct AssistantRequest: Sendable {
    public var task: AssistantTask
    public var requestID: String
    public var tabID: UUID?
    public var model: String?
    public var messages: [ChatMessage]
    public var page: PageContent?
    public var transcript: Transcript?
    public var selection: String?
    public var includeHistory: Bool

    public init(task: AssistantTask, requestID: String = UUID().uuidString, tabID: UUID? = nil, model: String? = nil,
                messages: [ChatMessage] = [], page: PageContent? = nil, transcript: Transcript? = nil,
                selection: String? = nil, includeHistory: Bool = false) {
        self.task = task
        self.requestID = requestID
        self.tabID = tabID
        self.model = model
        self.messages = messages
        self.page = page
        self.transcript = transcript
        self.selection = selection
        self.includeHistory = includeHistory
    }
}

