import Foundation

/// Assistant settings. Built from Preferences; development builds also accept the
/// `OLLAMA_HOST` / `ARC_AGENT_MODEL` environment variables (`OLLAMA_HOST=… make run`).
public struct AssistantConfiguration: Sendable, Equatable {
    public var baseURL: URL
    public var defaultModel: String?
    public var numCtx = 8192
    /// Characters of page/transcript text sent in one prompt before map-reduce kicks in.
    public var maxContextChars = 24_000
    public var chunkChars = 12_000
    public var requestTimeout: TimeInterval = 300
    public var keepAlive = "10m"
    /// SPKI SHA-256 pins (base64) the Ollama server must present; empty means system trust only.
    public var pinnedKeys: Set<String> = []

    public init(host: String? = nil, defaultModel: String? = nil) {
        self.baseURL = Self.normalizedHost(host)
        let model = defaultModel?.trimmingCharacters(in: .whitespaces)
        self.defaultModel = model?.isEmpty == false ? model : nil
    }

    @MainActor
    public static func fromPreferences(environment: [String: String] = ProcessInfo.processInfo.environment) -> Self {
        let defaults = UserDefaults.standard
        var host = defaults.string(forKey: Preferences.Key.ollamaHost)
        var model = defaults.string(forKey: Preferences.Key.agentModel)
        if !AppInfo.isPackaged {
            if host?.isEmpty ?? true { host = environment["OLLAMA_HOST"] }
            if model?.isEmpty ?? true { model = environment["ARC_AGENT_MODEL"] }
        }
        var configuration = Self(host: host, defaultModel: model)
        configuration.pinnedKeys = parsePins(defaults.string(forKey: Preferences.Key.ollamaPins))
        return configuration
    }

    /// Accepts the forms people put in OLLAMA_HOST: "", "0.0.0.0:11434", "myhost", "https://ollama.example".
    public static func normalizedHost(_ raw: String?) -> URL {
        let fallback = URL(string: "http://127.0.0.1:11434")!
        var host = (raw ?? "").trimmingCharacters(in: .whitespaces)
        guard !host.isEmpty else { return fallback }
        if !host.lowercased().hasPrefix("http://") && !host.lowercased().hasPrefix("https://") { host = "http://\(host)" }
        guard var parts = URLComponents(string: host), parts.host?.isEmpty == false else { return fallback }
        if parts.host == "0.0.0.0" { parts.host = "127.0.0.1" }
        if parts.port == nil, parts.scheme == "http" { parts.port = 11434 }
        // Never keep credentials from a pasted URL; they would end up in UserDefaults and logs.
        parts.user = nil
        parts.password = nil
        parts.path = ""
        parts.query = nil
        parts.fragment = nil
        return parts.url ?? fallback
    }

    public static func parsePins(_ raw: String?) -> Set<String> {
        Set((raw ?? "").split(whereSeparator: { $0 == "," || $0.isWhitespace }).map(String.init)
            .filter { Data(base64Encoded: $0)?.count == 32 })
    }

    /// Page content is sent to Ollama, so plain HTTP is only allowed to this Mac (loopback).
    public var transportError: IPCError? {
        guard baseURL.scheme == "http", let host = baseURL.host, !HTTPSFirst.isLoopback(host) else { return nil }
        return .ollamaUnavailable("Ollama at \(host) must use HTTPS: page content would cross the network unencrypted.")
    }
}

public enum AssistantTask: String, Sendable, CaseIterable {
    case chat
    case summarize
    case summarizeVideo = "summarize-video"
    case explainSelection = "explain-selection"
}

public struct ChatMessage: Codable, Sendable, Equatable {
    public enum Role: String, Codable, Sendable { case system, user, assistant }
    public var role: Role
    public var content: String

    public init(_ role: Role, _ content: String) {
        self.role = role
        self.content = content
    }
}

/// `dom.extract` result from injections/modules/dom-extractor.js.
public struct PageContent: Codable, Sendable, Equatable {
    public var url: String?
    public var title: String?
    public var byline: String?
    public var text: String?
    public var truncated: Bool?

    public init(url: String? = nil, title: String? = nil, byline: String? = nil, text: String? = nil, truncated: Bool? = nil) {
        self.url = url
        self.title = title
        self.byline = byline
        self.text = text
        self.truncated = truncated
    }
}

/// `youtube.transcript` result from injections/modules/youtube-transcript.js.
